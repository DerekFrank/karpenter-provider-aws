var (
	// e2eClusterName matches the cluster names that E2E workflows generate, e.g. "integration-123456" or "soak-periodic-123456"
	e2eClusterName = regexp.MustCompile(`^[a-z0-9-]+-[0-9]+$`)
	// keptClusterPrefixes are E2E-named clusters that are kept around on purpose and must never be swept
	keptClusterPrefixes = []string{"stk-"}
)

// isE2ECluster returns true if the cluster name was generated by an E2E workflow and isn't one we keep around
func isE2ECluster(name string) bool {
	return e2eClusterName.MatchString(name) && !lo.ContainsBy(keptClusterPrefixes, func(prefix string) bool { return strings.HasPrefix(name, prefix) })
}

// clusterChecker checks whether EKS clusters still exist, caching the answer for the duration of a sweep
type clusterChecker struct {
	eksClient *eks.Client
	gone      map[string]bool
}

func newClusterChecker(eksClient *eks.Client) *clusterChecker {
	return &clusterChecker{eksClient: eksClient, gone: map[string]bool{}}
}

// Gone returns true if DescribeCluster returns NotFound for the cluster in the client's region
func (c *clusterChecker) Gone(ctx context.Context, clusterName string) (bool, error) {
	if gone, ok := c.gone[clusterName]; ok {
		return gone, nil
	}
	_, err := c.eksClient.DescribeCluster(ctx, &eks.DescribeClusterInput{Name: lo.ToPtr(clusterName)})
	var notFound *ekstypes.ResourceNotFoundException
	if err != nil && !errors.As(err, &notFound) {
		return false, err
	}
	c.gone[clusterName] = err != nil
	return err != nil, nil
}

// Type is a resource type that can be cleaned through a cluster clean-up operation
// and through an expiration-based cleanup operation
type Type interface {
	// String is the string representation of the type
	String() string
	// Global determines if a resource is globally located in an account
	Global() bool
	// Get returns all resources of the type associated with the clusterName
	Get(ctx context.Context, clusterName string) (ids []string, err error)
	// GetExpired returns all resources of the type that were provisioned before the expirationTime
	GetExpired(ctx context.Context, expirationTime time.Time, excludedClusters []string) (ids []string, err error)
	// Cleanup deletes all resources of the type by id and returns the resource ids it succeeded to delete
	// In general, if all resources can't be deleted by id with a single API call (like with DeleteInstances)
	// you should call the requests synchronously to avoid rate limiting against the number of requests made
	Cleanup(ctx context.Context, ids []string) (cleaned []string, err error)
	// CountAll returns the number of all resource of the type in the account
	CountAll(ctx context.Context) (count int, err error)
}
